import { env } from './env';
import { getUser } from './telegram';

/**
 * Отправка событий воронки боту.
 *
 * ЗАЧЕМ. До 09.08.2026 воронка не измерялась вообще: на каком из тридцати с
 * лишним экранов люди отваливаются, сколько доходит до контроля качества,
 * сколько его проваливает и сколько вообще видит цену — неизвестно. Любые
 * дальнейшие правки без этого были бы вкусовщиной.
 *
 * КУДА. В бота, из которого человек и пришёл: `VITE_ANALYTICS_URL`. У бота уже
 * есть его Telegram id, подписка и канал связи — значит, он может не только
 * посчитать отвал, но и написать тому, кто дошёл до двадцать второго экрана и
 * не купил. Это и превращает воронку в автоворонку.
 *
 * ПОЧЕМУ `sendBeacon`. Самое ценное событие — последнее перед уходом, а
 * обычный `fetch` при закрытии мини-аппа успевает не всегда: браузер убивает
 * запрос вместе со страницей. `sendBeacon` ставит отправку в очередь браузера и
 * переживает закрытие. Отсюда и формат: тело — строка, ответ не читается.
 *
 * ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Не блокирует интерфейс, не бросает исключений и не
 * задерживает переход между экранами. Если адрес не задан — не делает ничего:
 * пустая переменная = честное выключенное состояние, как везде в проекте
 * (docs/SPEC.md §3.7). Воронка обязана проходиться без аналитики.
 *
 * ЧТО НЕ ОТПРАВЛЯЕТСЯ: ничего, кроме шага, района и Telegram id. Ни ответов
 * теста дословно, ни текстов — считать надо прохождение, а не человека.
 */

/** Метка запуска: отличает один проход воронки от другого у того же человека. */
const sessionId = createSessionId();

function createSessionId(): string {
  try {
    if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
      return crypto.randomUUID();
    }
  } catch {
    // Старый вебвью — обойдёмся меткой времени и случайным хвостом.
  }
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

export type FunnelEvent =
  /** Экран показан. Основа воронки отвала. */
  | 'step'
  /**
   * Такт сцены проигран. Шагов теперь восемь, и без этого события отвал внутри
   * минутного префрейма выглядел бы как отвал «на первом экране» — то есть не
   * говорил бы ничего. Считаем, на какой мысли человек закрывает приложение.
   */
  | 'beat'
  /** Глава: открыта, досмотрена, пропущена. */
  | 'lesson'
  /** Проверка перед лабораторией: пройдена, провалена, ушёл пересматривать. */
  | 'test'
  /** Связка собрана: участок встал на место. */
  | 'artifact'
  /** Нажата внешняя кнопка: ассистент, показанный сайт, оплата. */
  | 'external';

/**
 * Отправить событие. Никогда не бросает и ничего не ждёт.
 *
 * @param event что произошло
 * @param payload подробности события: шаг, район, исход
 */
export function track(event: FunnelEvent, payload: Record<string, string | number> = {}): void {
  const url = env.VITE_ANALYTICS_URL;
  if (!url) return;

  try {
    const user = getUser();
    const body = JSON.stringify({
      event,
      ...payload,
      sessionId,
      userId: user?.id ?? null,
      username: user?.username ?? null,
      at: new Date().toISOString(),
    });

    // Основной путь: переживает закрытие мини-аппа.
    if (typeof navigator !== 'undefined' && typeof navigator.sendBeacon === 'function') {
      navigator.sendBeacon(url, body);
      return;
    }

    // Запасной путь для вебвью без sendBeacon. `keepalive` просит браузер
    // довести запрос до конца, даже если страница закрывается.
    void fetch(url, {
      method: 'POST',
      body,
      keepalive: true,
      headers: { 'Content-Type': 'application/json' },
    }).catch(() => {
      // Молча: аналитика не имеет права ломать прохождение воронки.
    });
  } catch {
    // Тоже молча и по той же причине.
  }
}
