/**
 * Режим отладки.
 *
 * Включается флагом `?debug` в адресе. Ни пересборки, ни переменной окружения:
 * флаг можно дописать прямо к боевому адресу, проверить прохождение и убрать.
 * Живой человек панель отладки не увидит никогда.
 *
 * Живёт отдельно от компонента (`src/ui/DebugBar.tsx`) намеренно: файл, который
 * экспортирует и компонент, и функцию, ломает горячую перезагрузку в dev.
 */
export function isDebugEnabled(): boolean {
  try {
    return new URLSearchParams(window.location.search).has('debug');
  } catch {
    return false;
  }
}
