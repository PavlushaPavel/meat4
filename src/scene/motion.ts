/**
 * Словарь движения. ЕДИНСТВЕННОЕ место, где объявлены кривые, длительности и
 * пружины.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. К 11.08.2026 по проекту гуляли 22 разные
 * длительности, 6 разных пружин (ни одна не повторялась) и одна и та же кривая
 * `[0.16, 1, 0.3, 1]`, вписанная руками в 25 местах десяти файлов — при том что
 * в `tokens.css` уже лежал токен `--ease-snap` ровно с этим значением, которым
 * пользовался только мёртвый CSS.
 *
 * Само по себе это не ломало ничего: каждое значение по отдельности разумно.
 * Ломало другое — НЕВОЗМОЖНОСТЬ ПРАВИТЬ ОЩУЩЕНИЕ. Чтобы сделать движение чуть
 * спокойнее или чуть резче, пришлось бы поправить двадцать пять строк и одну
 * забыть. Личность интерфейса перестаёт быть решением и становится осадком.
 *
 * ПРАВИЛО: в компонентах не должно остаться ни одного числа времени и ни одной
 * кривой. Если нужного значения здесь нет — добавлять его сюда, а не вписывать
 * на месте.
 */

/** Кривая для motion: кортеж из четырёх чисел, как их принимает библиотека. */
export type Curve = [number, number, number, number];

export const ease: Record<'out' | 'inOut' | 'town', Curve> = {
  /**
   * Сильный ease-out. Начинается быстро — ровно в тот момент, когда человек
   * смотрит внимательнее всего. Значение совпадает с `--ease-snap` в
   * `tokens.css`; держать их в паре обязательно.
   *
   * Всё, что ПОЯВЛЯЕТСЯ и ИСЧЕЗАЕТ, использует его. `ease-in` в интерфейсе
   * запрещён: он тормозит на старте, и переход той же длины ощущается длиннее.
   */
  out: [0.16, 1, 0.3, 1],

  /**
   * Сильный ease-in-out. Только для того, что ПЕРЕМЕЩАЕТСЯ по экрану, не
   * появляясь и не исчезая: створки двери, отъезд камеры. У такого движения
   * есть разгон и торможение, потому что у него есть масса.
   */
  inOut: [0.77, 0, 0.175, 1],

  /**
   * Медленная городская кривая. Только для смены палитры акта — самого
   * долгого и самого фонового перехода в приложении. Совпадает с `--ease-town`.
   */
  town: [0.22, 0.61, 0.36, 1],
};

/**
 * Пять длительностей на всё приложение.
 *
 * Потолок интерфейсного движения — 300 мс; всё, что дольше, обязано быть
 * СОБЫТИЕМ, а не переходом. Отсюда разрыв между `screen` и `epic`: середины
 * нет намеренно, чтобы «просто подлиннее» нельзя было выбрать не думая.
 */
export const dur = {
  /** Отклик на нажатие. Человек должен увидеть ответ раньше, чем осознает. */
  press: 0.16,
  /** Мелкая подмена внутри блока: окно кабинета, точка, подпись. */
  quick: 0.22,
  /** Основная единица: появление и исчезновение чего угодно. */
  base: 0.3,
  /** Уровень экрана и крупных секций. */
  screen: 0.42,
  /**
   * Четыре дорогих эпизода и только они: въезд в город, подъём в Conversion
   * District, открытие дверей лаборатории, включение связки (DESIGN.md §7).
   */
  epic: 0.9,
} as const;

/**
 * Две пружины вместо шести.
 *
 * Записаны в форме «длительность + отскок», а не «жёсткость + затухание»:
 * так о них можно рассуждать, не решая в уме дифференциальное уравнение.
 * Отскок держится в пределах 0.1–0.2 — заметная упругость в этом мире
 * читалась бы как игрушечность, а город сварен из металла.
 */
export const spring = {
  /** Что-то ПРИЕХАЛО и встало на место: уведомление, деталь, экран-удар. */
  land: { type: 'spring', duration: 0.5, bounce: 0.2 },
  /** Короткая отметка состояния: галочка, минус жизни, открытый участок. */
  mark: { type: 'spring', duration: 0.34, bounce: 0.12 },
} as const;

/**
 * Два шага очереди — и это разные вещи, а не одно значение с разбросом.
 *
 * `list` — обычная выкладка списка: карточки, ступени, сегменты. Каталог
 * держит такой шаг в пределах 30–80 мс: длиннее — и интерфейс ощущается
 * медленным, а очередь начинает блокировать чтение.
 *
 * `reveal` — кинематографическое раскрытие внутри сцены: районы загораются
 * по одному, дороги прочерчиваются одна за другой. Здесь очередь и ЕСТЬ
 * содержание кадра, поэтому шаг втрое длиннее и это не ошибка.
 */
export const stagger = {
  list: 0.06,
  reveal: 0.16,
} as const;

/**
 * Обычный переход с кривой и длительностью.
 *
 * @param duration из `dur`, а не число руками
 * @param curve из `ease`; по умолчанию `out` — вход или выход
 */
export function tween(duration: number, curve: Curve = ease.out) {
  return { duration, ease: curve };
}

/**
 * Погасить движение, когда человек попросил его не показывать.
 *
 * ПОЧЕМУ ОДНА ФУНКЦИЯ НА ВЕСЬ ПРОЕКТ. Гейт `reduceMotion ? … : …` был
 * расставлен руками в двадцати с лишним местах, и в одном его забыли
 * (`SceneProgress`). Такую забывчивость нельзя поймать ни типами, ни линтом —
 * значит, гейт должен быть не дисциплиной, а функцией.
 *
 * Нулевая длительность, а не отсутствие перехода: состояние всё равно должно
 * смениться, просто мгновенно. Порядок событий при этом сохраняется —
 * катарсис не превращается в готовую картинку (docs/SPEC.md §2.1).
 */
export function calm<T extends object>(reduce: boolean | null, timing: T) {
  return reduce ? { duration: 0 } : timing;
}
