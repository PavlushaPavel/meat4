/**
 * Каркас сцены: АФИША, на которой автор рассказывает город.
 *
 * ПЕРЕСОБРАНО 13.08.2026 ПО РЕФЕРЕНСУ ЗАКАЗЧИКА, и это смена жанра, а не
 * раскладки. Было: кадр города в коробке сверху, под ним накопительный лог
 * реплик. Экран честно работал, но читался как СУБТИТРЫ К СЛАЙДШОУ — две
 * прямоугольные области, между которыми нет ничего общего.
 *
 * Стало то, что прислал заказчик: город на весь экран, автор вырезанной фигурой
 * в кадре, поверх — карточка голосового, крупный заголовок, подстрочник и
 * пузырь гида внизу. Все слои лежат в ОДНОЙ картинке, и человек смотрит не на
 * интерфейс с иллюстрацией, а на плакат, который говорит.
 *
 * ПОРЯДОК СЛОЁВ СНИЗУ ВВЕРХ И ПОЧЕМУ ОН ИМЕННО ТАКОЙ:
 *
 *  1. ГОРОД (`LivingCity`) — на весь экран, с медленным наездом. Он больше не
 *     сидит в коробке: у афиши нет полей, и именно это делает её афишей.
 *  2. ВИТРИНА ТАКТА (`stage`) — то, что город показывает СЕЙЧАС: окна кабинета,
 *     претензии клиента, связка. Прижата к правому краю, потому что слева стоит
 *     автор.
 *  3. АВТОР (`figure`) — вырезанная фигура, примерно на половину высоты. Стоит
 *     ПЕРЕД витриной: он ведущий, а не элемент схемы, и его рука в кадре
 *     перекрывает панель ровно так же, как перекрывала бы на съёмке.
 *  4. ЗАТЕМНЕНИЕ — не настроение, а требование читаемости: под текстом идёт
 *     живой кадр с фарами и окнами, и без этого слоя контраст букв менялся бы
 *     вместе с картинкой.
 *  5. РАМА И ТЕКСТ — единственное, что человек читает, и оно всегда сверху.
 *
 * ФИГУРА НЕ ПЕРЕКРЫВАЕТ ТЕКСТ ПО ПОСТРОЕНИЮ, а не по удачно подобранным
 * координатам: автор лежит слоем НИЖЕ затемнения, а текст — выше. Даже если
 * фигура доедет до нижней кромки экрана, она уйдёт под градиент, а не ляжет на
 * буквы.
 *
 * ЛОГА БОЛЬШЕ НЕТ — НА ЭКРАНЕ ТОЛЬКО ТЕКУЩАЯ РЕПЛИКА. Это осознанная потеря.
 * Лог существовал ровно по одной причине: у сцены не было перемотки, и
 * упущенную фразу нельзя было вернуть никак. Теперь перемотка есть, и назад
 * ведут два разных пути:
 *
 *  · ДОРОЖКА ПЛЕЕРА (`onSeek`) — в любую точку рассказа, вперёд и назад. Индекс
 *    такта в `useVoice` считается ОТ ПОЗИЦИИ В ЗАПИСИ, поэтому город и текст
 *    возвращаются вместе со звуком, а не остаются на месте;
 *  · ТАП ПО СЦЕНЕ — только вперёд, это ускоритель, а не навигация.
 *
 * ЧЕСТНАЯ ОГОВОРКА: пока записи нет, дорожка не притворяется перемоткой
 * (`VoicePlayer` сам выключает бегунок), сцену ведёт таймер, и назад вернуться
 * нельзя. Это то же самое состояние «записи ещё нет», в котором воронка уже
 * живёт, и оно уйдёт вместе с файлом озвучки — а не отдельной доработкой.
 */

/**
 * Насколько афиша приседает под пальцем.
 *
 * ЗАЧЕМ ВООБЩЕ. Тап по сцене — главный жест воронки, и до этого на него
 * отвечала одна вибрация. Вне Telegram её нет совсем (DESIGN.md §9), а внутри
 * нет уверенности, что человек её ощутит. Следующая реплика ответом не
 * считается: она приходит позже и читается как «сцена пошла дальше», а не как
 * «нажатие принято».
 *
 * ПОЧЕМУ 0.994, А НЕ 0.99. Приседает экран целиком, а не кнопка размером с
 * палец: те же проценты дают здесь ход в разы больше по абсолютной величине.
 * Заметное приседание всего экрана выглядит дёшево и укачивает; 0.6% — это
 * несколько пикселей по краю, ровно на грани осознания.
 */
const PRESS_SCALE = 0.994;

/**
 * Переключатель звука для сцены, у которой звука нет.
 *
 * ЧЕСТНОЕ СОСТОЯНИЕ, А НЕ ЗАГЛУШКА. Записан пока только вступление; подъём в
 * Conversion District и пятнадцать секунд города идут молча, и выключать там
 * буквально нечего. Кнопка рамы остаётся в положении «звук выключен» и говорит
 * правду: звука здесь нет.
 *
 * ЧТО БЫЛО БЫ ЛУЧШЕ. Чтобы кнопка не рисовалась вовсе, `SceneBottomBar` должен
 * принимать переключатель необязательным полем; сейчас он требует его всегда.
 * Пустой обработчик — временная плата за это, и она видна в одном месте, а не
 * размазана по экранам.
 */
function silence() {
  // Управлять нечем: у сцены без записи звука не существует.
}

/**
 * Голосовое, каким его видит сцена.
 *
 * НАМЕРЕННО УЖЕ, ЧЕМ `VoiceRun`: скорость воспроизведения и сам `BeatRun` сцене
 * не нужны — такт она получает отдельным полем. `VoiceRun` подходит сюда
 * структурно, поэтому на месте вызова ничего разбирать не приходится.
 */
export interface SceneVoice {
  /** Запись подключена. Ложь — сцену ведёт таймер, а прибор честно молчит. */
  available: boolean;
  /** Человек нажал воспроизведение хотя бы раз: рассказ пошёл. */
  started: boolean;
  playing: boolean;
  position: number;
  duration: number;
  start: () => void;
  toggle: () => void;
  seek: (ratio: number) => void;
  /**
   * Скорость и переключатель по кругу.
   *
   * Почти три минуты голоса на входе слушают по-разному: кто уже поймал мысль,
   * ускорится вместо того, чтобы бросить. Поле обязательное — сцена с записью
   * без выбора скорости это недоделка, а не вариант.
   */
  rate: number;
  cycleRate: () => void;
}

/**
 * ГОЛОС И ПОДПИСЬ ПЕРВОГО ДЕЙСТВИЯ ХОДЯТ ПАРОЙ, и это выражено типом, а не
 * договорённостью. Сцена с голосом обязана уметь сказать, чем она открывается
 * («Начать экскурсию»); сцена без голоса такой подписи не имеет и иметь не
 * должна — она стартует сама. Разложенные в два необязательных поля, они
 * однажды разъехались бы молча.
 */
type VoiceProps =
  | { voice: SceneVoice; startCta: string }
  | { voice?: undefined; startCta?: undefined };

type SceneShellProps<Cue extends string> = {
  run: BeatRun<Cue>;
  /** Сколько всего тактов — для полосы шагов в раме. */
  total: number;
  /** Витрина: то, что город показывает на текущем такте. */
  stage: ReactNode;
  /**
   * Полноэкранный слой ЗА фигурой автора.
   *
   * Витрина живёт в окне и по построению ограничена его краями. Всё, что должно
   * забрать экран целиком, окном обойтись не может — для этого и заведён
   * отдельный слой.
   */
  backdrop?: ReactNode;
  /**
   * Кадр города на весь экран (`public/intro/`). Без него афиша ложится на
   * сценографию шага из `CityStage` — так живут сцены, у которых своего города
   * нет (карта связки, например).
   */
  city?: string;
  /** Вырезанная фигура автора (`public/intro/`). Без неё витрина занимает всю ширину. */
  figure?: string;
  /** Подпись главного действия, которое появляется, когда сцена договорила. */
  cta: string;
  onCta: () => void;
  className?: string;
} & VoiceProps;

export function SceneShell<Cue extends string>(props: SceneShellProps<Cue>) {
  const { run, total, stage, backdrop, city, figure, cta, onCta, voice, startCta, className } =
    props;
  const reduceMotion = useReducedMotion();
  const { index, current, said, done, advance, finish } = run;

  /**
   * РАССКАЗ ЖДЁТ ПЕРВОГО НАЖАТИЯ, НО ОТДЕЛЬНОГО ЭКРАНА ВХОДА БОЛЬШЕ НЕТ.
   *
   * Раньше перед сценой стоял свой экран с пузырём голосового: сначала чат,
   * потом город. Заказчик попросил прямо противоположного — «он нажимает Play,
   * и в этот момент сам город начинает оживать». Поэтому первый кадр — ТА ЖЕ
   * афиша: город, автор, первая реплика, плеер на нуле. Не хватает ровно одного
   * — согласия слушать, и внизу вместо пузыря стоит приглашение начать.
   *
   * Жест по-прежнему обязателен, и не ради церемонии: без него браузер не даст
   * звук, а человек получит полторы минуты речи, на которые не соглашался.
   */
  const waiting = voice ? !voice.started : false;

  /** Сцена идёт: тап ведёт вперёд, пузырь-продолжение на месте. */
  const live = !waiting && !done;

  /**
   * Тап по сцене — жест выбора, а не удара: человек перелистывает мысль, а не
   * запускает событие мира. Отсюда `selectionChanged`, самый тихий отклик из
   * доступных. Вне Telegram вызов молча ничего не делает.
   */
  function tap() {
    if (!live) return;
    haptics.select();
    advance();
  }

  return (
    <motion.section
      className={cn('relative isolate flex h-dvh w-full flex-col overflow-hidden', className)}
      /**
       * Отклик на нажатие. `whileTap`, а не реакция на `onClick`: ответ обязан
       * прийти на прижатый палец, до того как жест закончится, — иначе это уже
       * не подтверждение, а последствие. Приседает афиша целиком от центра: у
       * полноэкранной картинки нет верха, за который её можно было бы держать.
       */
      whileTap={live && !reduceMotion ? { scale: PRESS_SCALE } : undefined}
      transition={calm(reduceMotion, tween(dur.press))}
    >
      {/*
        ГОРОД СМЕНЯЕТСЯ ПЕРЕТЕКАНИЕМ, А НЕ СКЛЕЙКОЙ. Кадров у вступления три, и
        меняются они на поворотах мысли — то есть посреди речи. Резкая подмена
        полноэкранной фотографии в этот момент читается как перезагрузка
        приложения; наплыв читается как переезд камеры, которого мы и добиваемся.
      */}
      <AnimatePresence initial={false}>
        {city && (
          <motion.div
            key={city}
            className="absolute inset-0"
            initial={reduceMotion ? false : { opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            transition={calm(reduceMotion, tween(dur.epic, ease.town))}
          >
            <LivingCity file={city} />
          </motion.div>
        )}
      </AnimatePresence>

      {/*
        ЗАДНИК — полноэкранный слой между городом и автором.
        Витрина такта живёт в окне и по построению ограничена его краями; всё,
        что должно ЗАБРАТЬ ЭКРАН, окном обойтись не может. Отсюда отдельный
        слой: он лежит за фигурой, поэтому растущее на нём не закрывает автора,
        и под затемнением, поэтому не спорит с текстом.
      */}
      {backdrop}

      <StageLayer narrow={Boolean(figure)}>{stage}</StageLayer>
      <Figure file={figure} />

      {/*
        Затемнение. Середина светлее краёв: сверху под рамой, снизу — под
        текстом, а в середине стоит автор, и гасить его незачем.
      */}
      <div
        aria-hidden="true"
        className="pointer-events-none absolute inset-0 bg-[linear-gradient(180deg,rgba(6,10,16,0.82)_0%,rgba(6,10,16,0.30)_18%,rgba(6,10,16,0.34)_40%,rgba(6,10,16,0.86)_62%,rgba(6,10,16,0.97)_78%,rgba(6,10,16,0.99)_100%)]"
      />

      {/*
        Слой нажатия. Он отдельный и лежит ПОД текстом, потому что тапать можно
        по всей афише, а органы управления должны получать свои нажатия сами.
        `div`, а не `button`: внутри афиши живут и кнопка плеера, и ползунок
        перемотки, а фокусируемый узел внутри кнопки — невалидная разметка,
        которая ломает и клавиатуру, и экранного диктора. Клавиатурный
        эквивалент — сам пузырь-продолжение ниже, он настоящая кнопка.
      */}
      {live && (
        <div role="presentation" onClick={tap} className="absolute inset-0" />
      )}

      <SceneTopBar className="pointer-events-auto relative shrink-0" />

      {/*
        Текст прижат к низу афиши и НИЧЕГО НЕ ЛОВИТ: сквозь него проходит тап по
        сцене. Ловят только органы управления, у каждого из них
        `pointer-events-auto` включён явно.
      */}
      <div className="pointer-events-none relative flex min-h-0 flex-1 flex-col justify-end gap-3 px-5 pb-3">
        <div className="relative flex flex-col gap-2">
          {voice && (
            /*
              КАРТОЧКА ГОЛОСОВОГО ВИСИТ НАД ТЕКСТОМ, А НЕ СТОИТ В КОЛОНКЕ.
              В потоке она съедала бы у автора сто с лишним пикселей высоты — то
              есть ровно то, что делает фигуру фигурой, а не аватаркой. На
              референсе она и лежит поверх кадра, перекрывая руку автора: это
              прибор на афише, а не строка интерфейса.
            */
            <div className="pointer-events-auto absolute inset-x-0 bottom-full mb-3">
              <VoicePlayer
                available={voice.available}
                playing={voice.playing}
                position={voice.position}
                duration={voice.duration}
                /*
                  Одна и та же кнопка открывает рассказ и ставит его на паузу.
                  Пока не начали — это и есть тот самый Play, после которого
                  город оживает; дальше это обычная пауза.
                */
                onToggle={waiting ? voice.start : voice.toggle}
                onSeek={voice.seek}
                rate={voice.rate}
                onRate={voice.cycleRate}
              />
            </div>
          )}

          {/*
            ПРИ ПРОСЬБЕ НЕ ДВИГАТЬ ЭКРАН РАССКАЗ ОТДАЁТСЯ ЦЕЛИКОМ, И ЭТО НЕ
            ИСКЛЮЧЕНИЕ РАДИ ГАЛОЧКИ. `useVoice` и `useBeats` в этом режиме сразу
            ставят последний такт и «договорила»: сцена не проигрывается вовсе.
            Пока внизу лежал лог, человек при этом видел весь текст. На афише
            текущая реплика одна — и тот же режим отдал бы ему ровно одну
            последнюю строку («Погнали.») вместо полутора минут рассказа.
            Поэтому здесь второй способ показать то же самое: не сцена, а текст.
          */}
          {reduceMotion ? <WholeText beats={said} /> : <BeatText beat={current} />}
        </div>

        <div className="flex items-end gap-3">
          <AnimatePresence mode="wait" initial={false}>
            {done ? (
              <motion.div
                key="cta"
                initial={reduceMotion ? false : { opacity: 0, y: 12 }}
                animate={{ opacity: 1, y: 0 }}
                transition={calm(reduceMotion, tween(dur.base))}
                className="pointer-events-auto min-w-0 flex-1"
              >
                <Button variant="hazard" onClick={onCta} arrow>
                  {cta}
                </Button>
              </motion.div>
            ) : waiting ? (
              <motion.div
                key="start"
                initial={reduceMotion ? false : { opacity: 0, y: 12 }}
                animate={{ opacity: 1, y: 0 }}
                transition={calm(reduceMotion, tween(dur.base))}
                className="pointer-events-auto min-w-0 flex-1"
              >
                {/*
                  Главное действие первого кадра. Не «слушать», а обещание пути:
                  человек соглашается не на полторы минуты звука, а на экскурсию
                  по городу. Подпись приходит из контента сцены-хозяина.
                */}
                <Button variant="hazard" onClick={voice?.start} arrow>
                  {startCta}
                </Button>
              </motion.div>
            ) : (
              <motion.button
                key="next"
                type="button"
                onClick={tap}
                initial={reduceMotion ? false : { opacity: 0, y: 12 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
                transition={calm(reduceMotion, tween(dur.base))}
                className="pointer-events-auto relative min-w-0 flex-1 rounded-2xl rounded-bl-sm border border-line bg-scene-deep/70 px-4 py-3 text-left backdrop-blur-md"
              >
                {/*
                  ПУЗЫРЬ ГИДА — ЕДИНСТВЕННЫЙ ВИДИМЫЙ ОРГАН УПРАВЛЕНИЯ РАССКАЗОМ,
                  и он же клавиатурный эквивалент тапа по афише.
                  Формулировка не «нажми, чтобы продолжить»: сцена идёт сама, и
                  такая подпись вернула бы механику «дальше» после каждой мысли,
                  от которой ушли (docs/SPEC.md §2.1). Сказано, что тап ускоряет,
                  а не что он нужен. Стрелка справа — то же самое знаком.
                */}
                <span className="legend text-ink">{sceneUi.tapHint}</span>
                <span
                  aria-hidden="true"
                  className="absolute bottom-3 right-4 text-lead leading-none text-hazard"
                >
                  ›
                </span>
              </motion.button>
            )}
          </AnimatePresence>

          {/*
            «ПРОПУСТИТЬ» ОСТАЁТСЯ, ХОТЯ НА РЕФЕРЕНСЕ ЕГО НЕТ. Человек, который
            читает быстрее любого темпа, обязан иметь выход — иначе рассказ
            превращается в ролик без перемотки. Приглушённой легендой сбоку: это
            не второе главное действие, а служебный выход.
          */}
          {live && (
            <button
              type="button"
              onClick={() => {
                haptics.light();
                finish();
              }}
              className="pointer-events-auto min-h-11 shrink-0 self-end px-1 text-legend uppercase tracking-legend text-ink-dim transition-colors hover:text-ink"
            >
              {sceneUi.skip}
            </button>
          )}
        </div>
      </div>

      <SceneBottomBar
        total={total}
        index={index}
        soundOn={Boolean(voice?.playing)}
        /*
          Звук в этом мире один — голос автора, поэтому кнопка рамы им и
          управляет: до старта запускает рассказ, дальше ставит на паузу и
          снимает с неё. У сцены без записи управлять нечем — см. `silence`.
        */
        onSound={voice ? (waiting ? voice.start : voice.toggle) : silence}
        className="pointer-events-auto relative shrink-0"
      />
    </motion.section>
  );
}

/**
 * Текущая реплика: крупный заголовок и подстрочник.
 *
 * ПЕРВАЯ СТРОКА ТАКТА — ЗАГОЛОВОК, ОСТАЛЬНЫЕ — ПОДСТРОЧНИК. Это не оформление,
 * а способ читать: на афише глаз сначала ловит крупное, и первой строкой автор
 * всегда произносит саму мысль, а дальше её разворачивает. Разделения на два
 * поля в такте нет и не нужно — сценарий правится как речь, а не как вёрстка
 * (`src/content/preframe.ts`).
 *
 * СМЕНА — ПОДМЕНОЙ, А НЕ ПЕРЕЛИВОМ. Реплика уходит целиком и приходит целиком:
 * переливающийся на месте текст читается как опечатка, которую исправляют.
 *
 * ОТСТАВАНИЕ `lead.cue` — то же правило, что было в логе: кадр идёт первым,
 * речь на два десятых позже. Иначе город и текст меняются в один момент в
 * разных местах экрана, глаз выбирает текст, и смена города пропадает впустую.
 *
 * `aria-live` обязателен именно теперь: сказанное больше не копится на экране, и
 * для того, кто слушает диктора, новая реплика — единственный источник рассказа.
 */
function BeatText({ beat }: { beat: Beat<string> }) {
  const reduceMotion = useReducedMotion();
  const [title, ...rest] = beat.say;

  return (
    <div aria-live="polite" className="relative min-h-0">
      {/*
        `popLayout`, А НЕ `wait`, И ЭТО НЕ ВКУС.
        При `wait` новая реплика ждёт, пока уйдёт прежняя, и один такт стоит
        0.16 + 0.2 + 0.3 секунды. Человек, который тапает быстрее, обгонял бы
        собственный текст: полоса шагов внизу и витрина уже на пятом такте, а на
        экране третий. Проверено на прогоне быстрыми нажатиями — расхождение
        доходило до девяти тактов. Здесь уходящая реплика вынимается из потока и
        гаснет отдельно, а новая приходит немедленно.
      */}
      <AnimatePresence mode="popLayout" initial={false}>
        <motion.div
          key={beat.id}
          initial={reduceMotion ? false : { opacity: 0, y: 12 }}
          animate={{ opacity: 1, y: 0 }}
          exit={reduceMotion ? undefined : { opacity: 0, transition: tween(dur.press) }}
          transition={calm(reduceMotion, { ...tween(dur.base), delay: lead.cue })}
          className="flex flex-col gap-1.5"
        >
          <h1
            className={cn(
              'text-balance font-display font-semibold text-ink',
              titleSize(title),
            )}
          >
            {title}
          </h1>
          {rest.map((line) => (
            <p key={line} className="text-balance text-small text-ink-dim">
              {line}
            </p>
          ))}
        </motion.div>
      </AnimatePresence>
    </div>
  );
}

/**
 * Весь рассказ текстом — режим «не двигать экран».
 *
 * ЧТО ЗДЕСЬ ПРОИСХОДИТ. Сцена в этом режиме не идёт: такты не сменяются, ждать
 * нечего, и человек имеет право получить всё сказанное сразу. Порядок прямой,
 * хронологический — это уже не лог сцены, за которым надо следить, а страница,
 * которую читают сверху вниз.
 *
 * ПРОКРУТКА ВНУТРИ ОБЛАСТИ, А НЕ СТРАНИЦЫ. Афиша ростом ровно в экран, и
 * растущий документ вернул бы ту самую поломку, из-за которой её пересобирали:
 * главное действие уехало бы за нижнюю кромку. Потолок в 44% высоты оставляет
 * на экране и карточку голосового, и кнопку.
 *
 * Первая строка первого такта остаётся заголовком: роль строки не должна
 * зависеть от системной настройки — иначе экранный диктор получает разную
 * структуру у одного и того же экрана.
 */
function WholeText({ beats }: { beats: readonly Beat<string>[] }) {
  return (
    <div className="relative">
      {/*
        Своя плоскость обязательна: это не две строки поверх города, а полторы
        минуты чтения, и под ними идёт кадр с вывесками и фарами. Материал тот
        же, что у карточки голосового и у витрин, — на афише плоскость одна.
      */}
      <div
        tabIndex={0}
        className="flex max-h-[44dvh] flex-col gap-3 overflow-y-auto overscroll-contain rounded-panel border border-line bg-scene-deep/82 p-3 outline-none backdrop-blur-md focus-visible:ring-1 focus-visible:ring-hazard/40"
      >
        {beats.map((beat, i) => (
          <div key={beat.id} className="flex flex-col gap-1">
            {beat.say.map((line, j) =>
              i === 0 && j === 0 ? (
                <h1
                  key={line}
                  className={cn(
                    'text-balance font-display font-semibold text-ink',
                    titleSize(line),
                  )}
                >
                  {line}
                </h1>
              ) : (
                <p key={line} className="text-balance text-small text-ink">
                  {line}
                </p>
              ),
            )}
          </div>
        ))}
      </div>

      {/*
        Нижняя кромка: текст растворяется, а не обрубается. Заодно это
        единственный признак, что ниже есть ещё, — полосы прокрутки в вебвью нет
        (`globals.css` прячет её на весь проект).
      */}
      <div
        aria-hidden="true"
        className="pointer-events-none absolute inset-x-px bottom-px h-10 rounded-b-panel bg-gradient-to-t from-scene-deep to-transparent"
      />
    </div>
  );
}

/**
 * Кегль заголовка подбирается по длине первой строки.
 *
 * ЗАЧЕМ, ЕСЛИ НА РЕФЕРЕНСЕ ОДИН КЕГЛЬ. На референсе заголовки короткие
 * («Знакомо?»), потому что их писали как заголовки. У нас заголовок — это ПЕРВАЯ
 * СТРОКА ЖИВОЙ РЕЧИ, и она бывает какой угодно: «Погнали.» и «…но одному клиент
 * спокойно платит тридцать тысяч, а другому — условные сто тридцать». Один
 * кегль на обе даёт либо мелкую вывеску, либо пять строк плаката, которые
 * наезжают на витрину и на карточку голосового. Проверено глазами: при 32px
 * длинная реплика занимала половину экрана.
 *
 * ПОРОГИ — ЭТО СТРОКИ, А НЕ ЗНАКИ. На 360px ширины крупный кегль держит около
 * двадцати знаков в строке, средний — около тридцати. Границы поставлены так,
 * чтобы заголовок укладывался в две строки, а самая длинная реплика — в четыре.
 *
 * ПОЧЕМУ НЕ ПОДГОНКА ИЗМЕРЕНИЕМ. Она дала бы точность и цену: заголовок
 * пересчитывался бы на каждом такте и подрагивал бы на глазах. Длина строки
 * известна заранее, и ступеней достаточно трёх.
 */
function titleSize(line: string): string {
  if (line.length <= 24) return 'text-hero';
  if (line.length <= 56) return 'text-title';
  return 'text-lead';
}

/**
 * Автор в кадре.
 *
 * РАЗМЕР ЗАДАН ДОЛЕЙ ЭКРАНА, А НЕ ПИКСЕЛЯМИ: фигура обязана читаться как
 * человек, стоящий в городе, и на любом телефоне занимать примерно половину
 * высоты. Пиксельная высота на 360×640 дала бы аватарку, а на 430×932 — великана.
 *
 * ФИГУРА СТОИТ СЛЕВА И ЗАХОДИТ ЗА КРАЙ. Так на референсе заказчика: голова
 * примерно на трети ширины, а дальнее плечо уходит из кадра. Это не небрежность
 * кадрирования, а его смысл — человек стоит БЛИЖЕ камеры, чем город, и потому
 * не помещается в неё целиком. Поставленная в край без выхода за него, фигура
 * читается как наклейка на фоне.
 *
 * ОБРЕЗАЕТСЯ ТОЛЬКО ДАЛЬНЕЕ ПЛЕЧО. Колба и жест — в правой части кадра, они
 * внутри всегда; по высоте фигуру держит `60dvh` вместе с нижней привязкой, и
 * макушка встаёт ниже рамы. `object-contain` не даёт ужать пропорцию.
 *
 * НИЗ УХОДИТ ПОД ТЕКСТ НАМЕРЕННО. Вырезка обрывается по поясу, и висящий в
 * воздухе торс выглядел бы браком; уходя под затемнение, он читается как
 * человек, стоящий ближе камеры, чем нижний край афиши.
 */
function Figure({ file }: { file?: string }) {
  const reduceMotion = useReducedMotion();

  return (
    <AnimatePresence initial={false}>
      {file && (
        <motion.img
          key={file}
          src={introAsset(file)}
          alt=""
          aria-hidden="true"
          initial={reduceMotion ? false : { opacity: 0, x: -14 }}
          animate={{ opacity: 1, x: 0 }}
          exit={{ opacity: 0 }}
          transition={calm(reduceMotion, tween(dur.screen))}
          className="pointer-events-none absolute bottom-[22%] left-[-10%] h-[60dvh] max-w-[80%] object-contain object-bottom drop-shadow-[0_24px_40px_rgba(0,0,0,0.65)]"
        />
      )}
    </AnimatePresence>
  );
}

/**
 * Ниже какого масштаба витрину уже не ужимаем.
 *
 * Дальше начинается нечитаемый шрифт на табличках и подписях, и честнее
 * обрезать край, чем показать мелкую кашу.
 */
const MIN_FIT = 0.62;

/**
 * Витрина такта: то, что город показывает сейчас.
 *
 * ЭТО НЕ КОРОБКА С КАДРОМ, А ОКНО В АФИШЕ. Прежний `StageBox` был прямоугольником
 * в потоке и отнимал у речи высоту; здесь витрина лежит слоем поверх города и
 * ничего у текста не забирает.
 *
 * ПОЧЕМУ ПРАВАЯ КОЛОНКА, А НЕ ВСЯ ШИРИНА. Слева стоит автор, и на референсе
 * панели города висят справа от него, частично уходя за его руку. Витрина шире
 * этой колонки не становится: она была бы наполовину скрыта фигурой, и в
 * скрытой половине оказывалось бы начало каждой панели — то есть самое важное.
 * Сцене без автора отдаётся вся ширина, и это не исключение, а то же правило.
 *
 * ПОДГОНКА МАСШТАБОМ ОСТАЁТСЯ. Такты показывают разное по высоте — от вывески
 * до связки из семи участков, — и одна фиксированная область на всех обязана
 * быть либо слишком большой, либо слишком маленькой. Витрина измеряет
 * содержимое и ужимает его ровно настолько, чтобы поместиться. Масштаб не
 * меняет размер элемента в раскладке, поэтому наблюдатель не зацикливается.
 */
function StageLayer({ children, narrow }: { children: ReactNode; narrow: boolean }) {
  const box = useRef<HTMLDivElement>(null);
  const inner = useRef<HTMLDivElement>(null);
  const [fit, setFit] = useState(1);

  useEffect(() => {
    // В тестовой среде наблюдателя нет: там раскладки не существует вовсе, и
    // мерить нечего. Витрина остаётся неужатой, разметка та же.
    if (typeof ResizeObserver === 'undefined') return;

    const measure = () => {
      const available = box.current?.clientHeight ?? 0;
      const natural = inner.current?.scrollHeight ?? 0;
      if (!available || !natural) return;
      setFit(natural <= available ? 1 : Math.max(MIN_FIT, available / natural));
    };

    const watch = new ResizeObserver(measure);
    if (box.current) watch.observe(box.current);
    if (inner.current) watch.observe(inner.current);
    measure();
    return () => watch.disconnect();
  }, []);

  return (
    <div
      ref={box}
      className={cn(
        // `items-start` — не оформление, а условие работы подгонки. При
        // растяжении по умолчанию высота внутреннего узла равна высоте коробки
        // всегда, и наблюдатель размеров не срабатывает НИ РАЗУ после первого
        // кадра: смена такта не меняет измеряемую величину. Витрина остаётся
        // неужатой, и связка обрезается по нижней кромке — ровно это и
        // произошло на такте `chain`.
        'pointer-events-none absolute flex items-start justify-end overflow-hidden',
        // Сцена с автором отдаёт витрине правую колонку и верхнюю треть: ниже
        // стоит фигура, левее — тоже она. Сцена без автора — всю ширину и
        // половину высоты: связка из семи участков в треть экрана вписывается
        // только масштабом 0.55, то есть подписями в шесть пикселей. Измерено,
        // а не прикинуто: при `40%` участок ПОСАДКА обрезался нижней кромкой.
        /*
          Витрина начинается НИЖЕ шапки, а не от края экрана. Проценты от высоты
          на 360×640 давали 58px — ровно под маркой и пилюлей платформы, и
          верхний угол витрины уезжал им под низ. Рама не прозрачная и не
          двигается, поэтому её высота — это просто занятое место, которое
          витрине не принадлежит.
        */
        narrow ? 'right-4 top-[15%] h-[38%] w-[62%]' : 'inset-x-5 top-[14%] h-[48%]',
      )}
    >
      <div
        ref={inner}
        // Опора — верх, а сторона зависит от того, есть ли в кадре автор. С ним
        // витрина жмётся к правой кромке рамы и ужимается «внутрь от угла»; без
        // него она занимает всю ширину, и опора по центру не даёт ужатой схеме
        // отъехать к одному краю.
        style={{
          transform: `scale(${fit})`,
          transformOrigin: narrow ? 'top right' : 'top center',
        }}
        className="w-full"
      >
        {children}
      </div>
    </div>
  );
}
