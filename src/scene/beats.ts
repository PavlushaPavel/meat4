/**
 * Такты сцены: единица, из которой собраны префрейм и подъём в Conversion
 * District (docs/SPEC.md §2.1).
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ПОЯВИЛОСЬ. Прежняя воронка резала мысль на экраны и после
 * каждой ставила кнопку «дальше». Тридцать одно нажатие до цены — это не
 * рассказ, а анкета. Здесь сцена идёт сама: автор говорит, город иллюстрирует,
 * человек ничего не нажимает. Такт — это одна мысль автора плюс то, что в
 * этот момент делает город.
 *
 * ПОЧЕМУ РЕПЛИКИ НЕ ИСЧЕЗАЮТ. Сказанное копится в логе, а не подменяется:
 * человек, который читает медленнее нашего темпа, иначе теряет фразу
 * безвозвратно и не может её вернуть — а перемотки у сцены нет. Текущая
 * реплика яркая, предыдущие приглушены и остаются на месте.
 */

/**
 * Один такт. Параметризован подсказкой сцены: у каждой сцены свой набор
 * состояний города, и подставить чужое нельзя — тип не даст.
 */
export interface Beat<Cue extends string> {
  /** Ключ такта. Нужен для анимации и для тестов, в интерфейсе не виден. */
  id: string;
  /** Что говорит автор. Каждая строка — отдельный абзац в логе. */
  say: readonly string[];
  /** Что в этот момент показывает город. */
  cue: Cue;
  /**
   * Сколько такт держится, мс. Если не задано — считается из длины реплики.
   * Задавать руками стоит только там, где нужна пауза по смыслу: перед
   * поворотом мысли или после вопроса, на который человек должен ответить
   * себе сам.
   */
  hold?: number;
}

/**
 * Сколько держать такт, если время не задано руками.
 *
 * Комфортное чтение по-русски — около шестнадцати знаков в секунду, отсюда
 * 60 мс на знак. Плюс секунда на то, чтобы глаз нашёл новую строку, и потолок,
 * чтобы длинная реплика не превращалась в паузу, в которой человек решит, что
 * приложение зависло.
 */
export function holdFor(beat: Beat<string>): number {
  if (beat.hold != null) return beat.hold;
  const chars = beat.say.join(' ').length;
  return Math.min(7000, Math.max(1900, 1000 + chars * 60));
}

/** Сколько идёт вся сцена. Нужен тестам и оценке «60–90 секунд». */
export function sceneDuration(beats: readonly Beat<string>[]): number {
  return beats.reduce((sum, beat) => sum + holdFor(beat), 0);
}
