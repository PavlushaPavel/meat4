/**
 * Момент в записи, куда отправляет кнопка «пересмотреть», задаётся полем
 * `reviewAt` каждого вопроса. СЕЙЧАС ОНО `null` У ВСЕХ ДВЕНАДЦАТИ, и это не
 * недоделка: три видео ещё не сняты и не смонтированы, таймкодов не существует.
 * Кнопка «Пересмотреть 08:42» на несуществующей записи — прямая ложь, а к
 * несуществующей секунде она не приведёт даже когда запись появится.
 *
 * ПОКА `reviewAt === null` кнопка называется «Пересмотреть первую часть» /
 * «Пересмотреть вторую часть» и ведёт на страницу нужного видео целиком.
 * КАК ТОЛЬКО ЗАПИСИ БУДУТ СМОНТИРОВАНЫ, сюда проставляются секунды — по одной
 * на вопрос, — и кнопка сама начнёт показывать время в формате М:СС. Ничего,
 * кроме этих чисел, править для этого не нужно.
 */
function timecode(seconds: number): string {
  const minutes = Math.floor(seconds / 60);
  return `${minutes}:${String(Math.floor(seconds % 60)).padStart(2, '0')}`;
}

/** Двузначный номер для приборной подписи: 03, 12. */
function pad(n: number): string {
  return String(n).padStart(2, '0');
}

