/**
 * Текст двух экранов, на которых смысл несёт КАРТА СВЯЗКИ, а не абзац.
 *
 * ПОЧЕМУ ОНИ В ОДНОМ ФАЙЛЕ. Шаг `audience` и шаг `bundle` разнесены маршрутом
 * (между ними два видео и проверка), но говорят они об одном и том же предмете:
 * в связку встаёт деталь. Первый — про первую деталь, второй — про все три и
 * про то, что из этого следует. Разложить их по разным файлам значит потерять
 * из виду, что финальная реплика обязана рифмоваться с первой наградой: «первый
 * кусок готов» → «у нас есть связка». Правя одну, видишь вторую.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ (сценарий заказчика от 11.08.2026):
 * ни отзывов, ни количества учеников, ни дедлайна, ни «осталось три места».
 * Единственная цифра в файле — цена. Подтверждать остальное нечем, а воронка,
 * которая врёт на последнем экране, обесценивает и всё сказанное до него.
 *
 * Имена участков связки, имя района и имя лаборатории СЮДА НЕ КОПИРУЮТСЯ: они
 * объявлены в `src/world.ts` (`ZONES`, `HOME_SOURCE`, `LAB_NAME`) и берутся
 * экранами оттуда. Одно имя в двух местах расходится ровно в тот день, когда
 * заказчик просит его переименовать.
 */

// ---------------------------------------------------------------------------
// Шаг `audience`: пятнадцать секунд города между первой и второй главой
// ---------------------------------------------------------------------------

/**
 * Что делает город на каждом такте короткой награды.
 *
 * `arrive` — снова город, деталь лежит в слоте над связкой, участок ещё серый;
 * `insert` — деталь физически уходит в связку, участок АУДИТОРИЯ загорается;
 * `lit`    — приборное подтверждение: AUDIENCE ✓;
 * `next`   — ничего не меняется, автор разворачивает человека во вторую главу.
 */
export type AudienceCue = 'arrive' | 'insert' | 'lit' | 'next';

/**
 * Награда, а не экран.
 *
 * Требование заказчика дословно: «Вот здесь опять появляется город. Не новый
 * экран с километром текста. Короткая награда». Отсюда четыре такта и ни одного
 * лишнего слова: суммарно четырнадцать секунд (проверяется `sceneDuration`, см.
 * `src/scene/beats.ts`). Всё, что человеку нужно унести отсюда, происходит на
 * втором такте — деталь встала на место, — а не написано текстом.
 *
 * Времена тактов НЕ ЗАДАНЫ РУКАМИ: `holdFor` считает их из длины реплики. Как
 * только текст правят, темп подстраивается сам; проставленные вручную паузы
 * пришлось бы пересчитывать, и кто-нибудь однажды забыл бы.
 */
export const audienceScene: {
  /** Подпись слота: какая по счёту деталь лежит над связкой. */
  slot: string;
  /** Имя детали на плитке. Вывеска участка, а не термин. */
  part: string;
  /** Приборное подтверждение после того, как участок загорелся. */
  lit: string;
  /** Единственное действие экрана. */
  cta: string;
  beats: readonly Beat<AudienceCue>[];
} = {
  slot: 'ДЕТАЛЬ 01',
  part: 'AUDIENCE',
  lit: 'AUDIENCE ✓',
  cta: 'Собрать предложение',

  beats: [
    {
      id: 'arrive',
      cue: 'arrive',
      say: ['Первый кусок готов.'],
    },
    {
      id: 'insert',
      cue: 'insert',
      say: ['Теперь мы знаем, кому продаём и почему он вообще хочет купить.'],
    },
    {
      // Поворот стоит РЯДОМ с наградой, а не после паузы: участок загорелся —
      // и тут же выясняется, что этого мало. Иначе человек успевает решить,
      // что дело сделано, и вторая глава начинается с пустого места.
      id: 'lit',
      cue: 'lit',
      say: ['Но знать человека мало.'],
    },
    {
      id: 'next',
      cue: 'next',
      say: ['Нужно ещё нормально объяснить ему, почему покупать стоит у нас.'],
    },
  ],
};

