import type { ArtifactId } from '@/world';

/**
 * Типы контента воронки.
 *
 * Весь текст живёт в `src/content/*` и больше нигде. В компонентах нет ни одной
 * строки копирайта — это правило канона (docs/SPEC.md §4.5), а не совпадение.
 *
 * Ритм авторского текста — короткие абзацы, часто в одно предложение. Каждый
 * абзац здесь отдельный блок: склеивать их в плотные куски запрещено, на этом
 * ритме держится подача.
 */

/** Блок текста. */
export type Block =
  /** Обычный абзац. */
  | { kind: 'p'; text: string }
  /** Врезка-реплика: чужой или внутренний голос. */
  | { kind: 'quote'; text: string }
  /** Крупное утверждение, ради которого написан кусок. Одно на раздел. */
  | { kind: 'lead'; text: string }
  /** Перечисление. Пункты короткие, без точек в конце. */
  | { kind: 'list'; items: string[] }
  /** Подзаголовок. */
  | { kind: 'h'; text: string };

/**
 * Кнопка на внешний ресурс. Пустая переменная сборки = кнопка честно неактивна
 * с подписью, а не мёртвый переход в никуда (docs/SPEC.md §3.7).
 */
export interface ExternalAction {
  label: string;
  /** Что написано, пока ссылки нет. */
  pending: string;
  envVar:
    | 'VITE_ASSISTANT_AUDIENCE_URL'
    | 'VITE_ASSISTANT_OFFER_URL'
    | 'VITE_LANDING_DEMO_URL'
    | 'VITE_CHECKOUT_URL'
    | 'VITE_SUPPORT_URL';
}

// ---------------------------------------------------------------------------
// Обучение: три видеостраницы
// ---------------------------------------------------------------------------

/**
 * Раздел конспекта. Видео — главное на странице, но воронка обязана быть
 * проходимой и понятной без единой записи: конспект несёт смысл главы сам.
 */
export interface LessonSection {
  title: string;
  items: readonly string[];
  /**
   * Раздел, в котором на экране появляется ассистент. Помечается отдельно,
   * потому что первый AI-wow должен быть виден в оглавлении главы, а не
   * растворяться в списке тем: ради него человек и досматривает.
   */
  ai?: boolean;
}

/** Что человек уносит из главы. Артефакт копится и переезжает в следующую. */
export interface ArtifactCard {
  id: ArtifactId;
  /** Имя на карточке: AUDIENCE REPORT. */
  name: string;
  /** Из чего он состоит. Это же показывается галочками в следующей главе. */
  lines: readonly string[];
  /** Ссылка на ассистента, если она вообще есть. */
  action?: ExternalAction;
}

/** Видеостраница. Записей пока нет — экран обязан работать без источника. */
export interface LessonContent {
  /** Номер главы: 01, 02, 03. */
  number: string;
  /** Короткое имя главы для полосы прогресса: «Аудитория». */
  short: string;
  title: string;
  standfirst: string;
  envVar: 'VITE_VIDEO_1_URL' | 'VITE_VIDEO_2_URL' | 'VITE_VIDEO_3_URL';
  /**
   * Что уже лежит в проекте к началу этой главы. Пусто у первой; дальше —
   * то, ради чего вся конструкция: следующая глава не начинается с нуля.
   */
  carried: readonly string[];
  /** Вступление автора: почему глава начинается именно отсюда. */
  intro: readonly Block[];
  outline: readonly LessonSection[];
  output: ArtifactCard;
  /** Подпись кнопки перехода дальше. */
  next: string;
}

// ---------------------------------------------------------------------------
// Проверка перед лабораторией
// ---------------------------------------------------------------------------

/** Тема вопроса — по ней выбираем, какое видео отправить пересматривать. */
export type QuizTopic = 'audience' | 'offer';

export interface QuizOption {
  id: string;
  text: string;
}

export interface QuizQuestion {
  id: string;
  topic: QuizTopic;
  /** Ситуация. Вопрос всегда начинается с неё, а не с определения. */
  situation: string;
  question: string;
  options: readonly QuizOption[];
  correctId: string;
  /**
   * Разбор. Говорит о РЕШЕНИИ, а не о термине: «здесь ты снова выбираешь
   * человека по внешнему признаку, а не по ситуации покупки». Проверять
   * расшифровку аббревиатуры запрещено (docs/SPEC.md §3.5).
   */
  explanation: string;
  /**
   * Секунда в видео, куда вернуть человека после ошибки. `null`, пока запись
   * не снята: выдуманный таймкод на несуществующем видео — ложь, а кнопка
   * «пересмотреть 08:42», которая никуда не ведёт, хуже её отсутствия.
   * Появится значение — кнопка сама начнёт показывать время.
   */
  reviewAt: number | null;
}
