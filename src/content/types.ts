/**
 * Человек на портрете: один из пяти, кто ввёл одинаковый запрос.
 *
 * Портрет лежит в `public/samples/{code}.webp` и берётся ПО НОМЕРУ, а не по
 * отдельному полю с путём: путь, который можно задать руками, рано или поздно
 * разойдётся с номером на карточке, и человек увидит образец 03 с лицом от 05.
 */
export interface SamplePerson {
  id: string;
  /**
   * Номер образца: 01…05. Он же имя файла портрета и он же ЗАПАСНОЕ содержимое
   * карточки — если картинка не загрузилась, на её месте остаётся крупный
   * номер, а не битая иконка и не пустой прямоугольник (docs/SPEC.md §3.7).
   */
  code: string;
  /** Имя ситуации на карточке: «Новостройка», «Федя». */
  label: string;
  /** Что у него происходит. Одна-две короткие фразы — карточка узкая. */
  situation: string;
  /**
   * Тот, на ком ломается логика «по запросу подходит». Строка — пометка,
   * которая объясняет выделение прямо на карточке. Поле СОЗНАТЕЛЬНО одно, а не
   * пара «флаг + текст»: выделить человека, не сказав за что, невозможно по
   * построению — а без объяснения выделение читается как насмешка.
   */
  pivot?: string;
}

/**
 * Врезка с портретами внутри раздела конспекта. Не задание и не выбор: автор
 * показывает людей на записи, зритель их разглядывает (`src/content/people.ts`).
 */
export interface PeopleBlock {
  /** Трафаретная подпись над лентой. */
  legend: string;
  /** Сам запрос, из которого всё растёт. */
  query: string;
  /** Имя ленты для скринридера: вбок она прокручивается только глазами. */
  rowAria: string;
  people: readonly SamplePerson[];
  /** Вывод под лентой — то, ради чего врезка стоит в этом разделе. */
  caption: string;
}

/**
 * Раздел конспекта. Видео — главное на странице, но воронка обязана быть
 * проходимой и понятной без единой записи: конспект несёт смысл главы сам.
 */
export interface LessonSection {
  title: string;
  items: readonly string[];
  /**
   * Раздел, в котором на экране появляется ассистент. Помечается отдельно,
   * потому что первый AI-wow должен быть виден в оглавлении главы, а не
   * растворяться в списке тем: ради него человек и досматривает.
   */
  ai?: boolean;
  /**
   * Портреты внутри раздела. Есть ровно у одного раздела воронки — «Федя и
   * реновация»: там мысль держится на том, что пятерых нельзя различить по
   * запросу, и её надо ПОКАЗАТЬ. Развесить ленту по остальным разделам значит
   * превратить её в оформление.
   */
  people?: PeopleBlock;
}

/** Что человек уносит из главы. Артефакт копится и переезжает в следующую. */
export interface ArtifactCard {
  id: ArtifactId;
  /** Имя на карточке: AUDIENCE REPORT. */
  name: string;
  /** Из чего он состоит. Это же показывается галочками в следующей главе. */
  lines: readonly string[];
  /** Ссылка на ассистента, если она вообще есть. */
  action?: ExternalAction;
}

/** Видеостраница. Записей пока нет — экран обязан работать без источника. */
export interface LessonContent {
  /** Номер главы: 01, 02, 03. */
  number: string;
  /** Короткое имя главы для полосы прогресса: «Аудитория». */
  short: string;
  title: string;
  standfirst: string;
  envVar: 'VITE_VIDEO_1_URL' | 'VITE_VIDEO_2_URL' | 'VITE_VIDEO_3_URL';
  /**
   * Что уже лежит в проекте к началу этой главы. Пусто у первой; дальше —
   * то, ради чего вся конструкция: следующая глава не начинается с нуля.
   */
  carried: readonly string[];
  /** Вступление автора: почему глава начинается именно отсюда. */
  intro: readonly Block[];
  outline: readonly LessonSection[];
  output: ArtifactCard;
  /** Подпись кнопки перехода дальше. */
  next: string;
}

