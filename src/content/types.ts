/** Тема вопроса — по ней выбираем, какое видео отправить пересматривать. */
export type QuizTopic = 'audience' | 'offer';

export interface QuizOption {
  id: string;
  text: string;
}

export interface QuizQuestion {
  id: string;
  topic: QuizTopic;
  /** Ситуация. Вопрос всегда начинается с неё, а не с определения. */
  situation: string;
  question: string;
  options: readonly QuizOption[];
  correctId: string;
  /**
   * Разбор. Говорит о РЕШЕНИИ, а не о термине: «здесь ты снова выбираешь
   * человека по внешнему признаку, а не по ситуации покупки». Проверять
   * расшифровку аббревиатуры запрещено (docs/SPEC.md §3.5).
   */
  explanation: string;
  /**
   * Секунда в видео, куда вернуть человека после ошибки. `null`, пока запись
   * не снята: выдуманный таймкод на несуществующем видео — ложь, а кнопка
   * «пересмотреть 08:42», которая никуда не ведёт, хуже её отсутствия.
   * Появится значение — кнопка сама начнёт показывать время.
   */
  reviewAt: number | null;
}
