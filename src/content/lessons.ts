/**
 * Оглавление курса для полосы прогресса: 1. Аудитория → 2. Оффер → 3. Посадка.
 *
 * Порядок берётся из МАРШРУТА (`ACT_STEPS.study`), а не переписан руками:
 * иначе полоса и воронка со временем разъедутся, и человек увидит «2. Оффер»,
 * находясь в третьей главе. Номер в полосе рисуется из позиции — цифра
 * копирайтом не является и в контенте ей делать нечего.
 */
export const CHAPTERS: readonly { step: LessonStep; short: string }[] =
  ACT_STEPS.study
    .filter((step): step is LessonStep => step in LESSONS)
    .map((step) => ({ step, short: LESSONS[step].short }));

