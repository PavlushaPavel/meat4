/**
 * Маршрут воронки: ВОСЕМЬ состояний, три акта, линейно, с одной точкой возврата.
 *
 * ПЕРЕСОБРАНО 11.08.2026 под архитектуру «девять состояний» (docs/SPEC.md §2).
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ПРЕЖНЕЙ ВОРОНКИ И ПОЧЕМУ. Предыдущая редакция резала
 * мысль на экраны: тридцать один шаг, и после каждой мысли человек жал «дальше».
 * Это превращало префрейм в чтение с кнопкой. Здесь наоборот: префрейм — ОДНА
 * сцена на 60–90 секунд, которая идёт сама, а город иллюстрирует сказанное.
 * Экран меняется не когда закончилась мысль, а когда меняется РЕЖИМ работы
 * человека: он смотрел сцену — стал смотреть видео — стал отвечать на вопросы.
 *
 * Отсюда правило, которое нельзя нарушать: НОВЫЙ ШАГ ПОЯВЛЯЕТСЯ ТОЛЬКО ТОГДА,
 * КОГДА МЕНЯЕТСЯ РЕЖИМ. Всё остальное — такты внутри шага (`src/scene/beats.ts`).
 *
 * Девять состояний продукта против восьми шагов маршрута: продажа за 3 990 ₽
 * живёт на том же экране, что и собранная связка, и раскрывается после
 * возвращения человека с показанного сайта. Отдельным шагом она не является.
 */

